  /* ---------- 工具函数 ---------- */
  var LANG_KEY = 'halo.lang';

  function loadLang() {
    var c = localStorage.getItem(LANG_KEY);
    if (c && D[c]) return c;
    // 检测浏览器语言
    var nav = navigator.language || '';
    if (nav.startsWith('zh')) return 'zh';
    if (nav.startsWith('ja')) return 'ja';
    if (nav.startsWith('ko')) return 'ko';
    if (nav.startsWith('es')) return 'es';
    if (nav.startsWith('fr')) return 'fr';
    if (nav.startsWith('de')) return 'de';
    if (nav.startsWith('pt')) return 'pt';
    return 'zh';
  }

  function saveLang(code) {
    if (D[code]) localStorage.setItem(LANG_KEY, code);
  }

  /* ---------- 翻译 ---------- */
  function t(key, vars) {
    var lang = _currentLang || loadLang();
    var dict = D[lang] || D['zh'];
    var val = dict[key];
    if (val === undefined) {
      // 回退到中文
      val = D['zh'][key];
    }
    if (val === undefined) return key;
    if (!vars) return val;

    var str = String(val);

    if (Array.isArray(vars)) {
      // 数组：先替换数字索引 %0, %1, %2...
      vars.forEach(function (v, i) {
        str = str.replace(new RegExp('%' + i, 'g'), String(v));
      });
      // 再替换类型化占位符 %d, %s, %n（按顺序取前3个元素）
      str = str.replace(/%d/g, vars[0] !== undefined ? String(vars[0]) : '%d');
      str = str.replace(/%s/g, vars[1] !== undefined ? String(vars[1]) : '%s');
      str = str.replace(/%n/g, vars[2] !== undefined ? String(vars[2]) : '%n');
    } else {
      // 单个值：替换所有 %d, %s, %n
      str = str.replace(/%[dsn]/g, String(vars));
    }
    return str;
  }

  function setLang(code) {
    if (!D[code]) return false;
    _currentLang = code;
    saveLang(code);
    return true;
  }

  function getLang() {
    return _currentLang || loadLang();
  }

  var _currentLang = null;

